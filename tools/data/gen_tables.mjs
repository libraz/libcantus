#!/usr/bin/env node
/**
 * Generate the C++ data tables and limit constants from the evaluated pure-TS modules.
 *
 * Every module directory of the C++ tree (src/<layer>/ and src/<layer>/<module>/ holding a
 * CMakeLists.txt) gets a limits.gen.h. A directory with a tables.json also gets one
 * <snake_export>.gen.inc per table: the braced initializer of the C++ array, rows in TS order and
 * fields in the order tables.json lists them.
 *
 * tables.json:
 *   {
 *     "tables": [{ "module": "theory/chord/spec.ts", "export": "QUALITY_SPECS",
 *                  "cxx_type": "QualitySpec", "cxx_name": "kQualitySpecs",
 *                  "fields": ["name", { "name": "tones", "fields": ["degree", "optional"] }] }],
 *     "limits": [{ "module": "core/random/version.ts", "export": "ALGORITHM_VERSION",
 *                  "cxx_type": "std::uint32_t" }]
 *   }
 * `module` is relative to ts/src. An array export gives one row per element; an object export
 * gives one `{"key", value}` row per entry; with `"form": "record"` the object export is one
 * record, written as a single braced initializer of its `fields`. Absent values become
 * std::nullopt.
 *
 * Usage:
 *   node tools/data/gen_tables.mjs              write every generated file
 *   node tools/data/gen_tables.mjs --check      fail when a generated file is stale or orphaned
 *   node tools/data/gen_tables.mjs --check --require
 *                                               also fail when no tables.json exists
 *   node tools/data/gen_tables.mjs --self-test  run the generator against tools/data/fixtures
 *   --root <dir>                                 another tree (tools/data/fixtures/root)
 */
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '../..');
const LAYERS = ['core', 'theory', 'analyze', 'generate', 'model'];
const HEADER = '// Generated by tools/data/gen_tables.mjs from ts/src; do not edit.';

const INTEGER_TYPES = {
  int: [-2147483648, 2147483647],
  'std::int32_t': [-2147483648, 2147483647],
  'std::uint32_t': [0, 4294967295],
  'std::int64_t': [Number.MIN_SAFE_INTEGER, Number.MAX_SAFE_INTEGER],
  'std::uint64_t': [0, Number.MAX_SAFE_INTEGER],
  'std::size_t': [0, Number.MAX_SAFE_INTEGER],
};
const LIMIT_TYPES = new Set([...Object.keys(INTEGER_TYPES), 'double', 'bool']);

class GenError extends Error {}

function say(line) {
  process.stdout.write(`${line}\n`);
}

/** Load ts/src modules of `root` through Vite's module runner (the successor of vite-node). */
async function createLoader(root) {
  const { createServer, createServerModuleRunner } = await import('vite');
  const server = await createServer({
    root,
    configFile: false,
    logLevel: 'error',
    appType: 'custom',
    server: { middlewareMode: true, hmr: false, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  const runner = createServerModuleRunner(server.environments.ssr, { hmr: false });
  const cache = new Map();
  return {
    async load(module) {
      if (!cache.has(module)) {
        const file = join(root, 'ts/src', module);
        if (!existsSync(file)) {
          throw new GenError(`ts/src/${module} does not exist`);
        }
        cache.set(module, await runner.import(file));
      }
      return cache.get(module);
    },
    async close() {
      await runner.close();
      await server.close();
    },
  };
}

/** Directories of the C++ tree that hold module sources, relative to `root`. */
function moduleDirs(root) {
  const dirs = [];
  for (const layer of LAYERS) {
    const layerDir = join(root, 'src', layer);
    if (!existsSync(join(layerDir, 'CMakeLists.txt'))) {
      continue;
    }
    dirs.push(`src/${layer}`);
    for (const entry of readdirSync(layerDir, { withFileTypes: true })) {
      if (entry.isDirectory() && existsSync(join(layerDir, entry.name, 'CMakeLists.txt'))) {
        dirs.push(`src/${layer}/${entry.name}`);
      }
    }
  }
  return dirs.sort();
}

function snake(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .replace(/[^A-Za-z0-9]+/g, '_')
    .toLowerCase();
}

function guard(dir) {
  return `CANTUS_${dir.replace(/[^A-Za-z0-9]+/g, '_').toUpperCase()}_LIMITS_GEN_H_`;
}

/** A C++ literal for a JS number. */
function numberLiteral(x, where) {
  if (typeof x !== 'number') {
    throw new GenError(`${where}: expected a number, got ${typeof x}`);
  }
  if (Number.isNaN(x)) return 'std::numeric_limits<double>::quiet_NaN()';
  if (x === Infinity) return 'std::numeric_limits<double>::infinity()';
  if (x === -Infinity) return '-std::numeric_limits<double>::infinity()';
  if (Object.is(x, -0)) return '-0.0';
  return String(x);
}

/** A C++ narrow string literal holding the WTF-8 bytes of a JS string. */
function stringLiteral(s) {
  let out = '"';
  for (let i = 0; i < s.length; i++) {
    let cp = s.charCodeAt(i);
    if (cp >= 0xd800 && cp <= 0xdbff && i + 1 < s.length) {
      const lo = s.charCodeAt(i + 1);
      if (lo >= 0xdc00 && lo <= 0xdfff) {
        cp = 0x10000 + ((cp - 0xd800) << 10) + (lo - 0xdc00);
        i++;
      }
    }
    if (cp === 0x22 || cp === 0x5c) {
      out += `\\${String.fromCharCode(cp)}`;
    } else if (cp >= 0x20 && cp < 0x7f) {
      out += String.fromCharCode(cp);
    } else {
      for (const byte of wtf8(cp)) {
        out += `\\${byte.toString(8).padStart(3, '0')}`;
      }
    }
  }
  return `${out}"`;
}

function wtf8(cp) {
  if (cp < 0x80) return [cp];
  if (cp < 0x800) return [0xc0 | (cp >> 6), 0x80 | (cp & 0x3f)];
  if (cp < 0x10000) return [0xe0 | (cp >> 12), 0x80 | ((cp >> 6) & 0x3f), 0x80 | (cp & 0x3f)];
  return [
    0xf0 | (cp >> 18),
    0x80 | ((cp >> 12) & 0x3f),
    0x80 | ((cp >> 6) & 0x3f),
    0x80 | (cp & 0x3f),
  ];
}

/** The initializer of `value`; `fields` orders the members of an object (and of each element). */
function initializer(value, fields, where) {
  if (value === undefined || value === null) return 'std::nullopt';
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  if (typeof value === 'number') return numberLiteral(value, where);
  if (typeof value === 'string') return stringLiteral(value);
  if (Array.isArray(value)) {
    return `{${value.map((e, i) => initializer(e, fields, `${where}[${i}]`)).join(', ')}}`;
  }
  if (typeof value === 'object') {
    if (!fields) {
      throw new GenError(`${where}: an object needs a "fields" list`);
    }
    const parts = fields.map((f) => {
      const name = typeof f === 'string' ? f : f.name;
      return initializer(
        value[name],
        typeof f === 'string' ? undefined : f.fields,
        `${where}.${name}`,
      );
    });
    return `{${parts.join(', ')}}`;
  }
  throw new GenError(`${where}: cannot write a ${typeof value} as C++`);
}

async function exportOf(loader, spec, where) {
  if (typeof spec.module !== 'string' || typeof spec.export !== 'string') {
    throw new GenError(`${where}: "module" and "export" are required`);
  }
  const mod = await loader.load(spec.module);
  if (!(spec.export in mod)) {
    throw new GenError(`${where}: ts/src/${spec.module} has no export ${spec.export}`);
  }
  return mod[spec.export];
}

async function tableFile(loader, dir, spec) {
  const where = `${dir}/tables.json ${spec.export}`;
  for (const key of ['cxx_type', 'cxx_name', 'fields']) {
    if (spec[key] === undefined) {
      throw new GenError(`${where}: "${key}" is required`);
    }
  }
  const value = await exportOf(loader, spec, where);
  if (spec.form === 'record') {
    if (value === null || typeof value !== 'object' || Array.isArray(value)) {
      throw new GenError(`${where}: a record export must be a plain object`);
    }
    return [
      HEADER,
      `// ${spec.export} (ts/src/${spec.module}): initializer of ${spec.cxx_type} ${spec.cxx_name}.`,
      initializer(value, spec.fields, spec.export),
      '',
    ].join('\n');
  }
  if (spec.form !== undefined) {
    throw new GenError(`${where}: unknown "form" ${JSON.stringify(spec.form)}`);
  }
  let rows;
  if (Array.isArray(value)) {
    rows = value.map((e, i) => initializer(e, spec.fields, `${spec.export}[${i}]`));
  } else if (value !== null && typeof value === 'object') {
    rows = Object.entries(value).map(([k, v]) => {
      const inner = initializer(
        v,
        spec.fields.length > 0 ? spec.fields : undefined,
        `${spec.export}.${k}`,
      );
      return `{${stringLiteral(k)}, ${inner}}`;
    });
  } else {
    throw new GenError(`${where}: a table export must be an array or an object`);
  }
  const body = rows.map((r) => `    ${r},`).join('\n');
  return [
    HEADER,
    `// ${spec.export} (ts/src/${spec.module}): initializer of ${spec.cxx_type} ${spec.cxx_name}[].`,
    rows.length === 0 ? '{}' : `{\n${body}\n}`,
    '',
  ].join('\n');
}

async function limitLine(loader, dir, spec) {
  const where = `${dir}/tables.json ${spec.export}`;
  if (!LIMIT_TYPES.has(spec.cxx_type)) {
    throw new GenError(`${where}: cxx_type must be one of ${[...LIMIT_TYPES].join(', ')}`);
  }
  const value = await exportOf(loader, spec, where);
  const name = spec.cxx_name ?? spec.export;
  let literal;
  if (spec.cxx_type === 'bool') {
    if (typeof value !== 'boolean') throw new GenError(`${where}: expected a boolean`);
    literal = String(value);
  } else if (spec.cxx_type === 'double') {
    literal = numberLiteral(value, where);
  } else {
    const [lo, hi] = INTEGER_TYPES[spec.cxx_type];
    if (typeof value !== 'number' || !Number.isInteger(value) || value < lo || value > hi) {
      throw new GenError(`${where}: ${String(value)} is not a ${spec.cxx_type}`);
    }
    literal = String(value);
  }
  return [
    `/** ${spec.export} of ts/src/${spec.module}. */`,
    `inline constexpr ${spec.cxx_type} ${name} = ${literal};`,
  ];
}

function limitsHeader(dir, lines) {
  const g = guard(dir);
  const out = [HEADER, `#ifndef ${g}`, `#define ${g}`, ''];
  if (lines.length > 0) {
    const text = lines.flat().join('\n');
    if (text.includes('std::numeric_limits')) out.push('#include <limits>');
    if (/std::u?int\d+_t/.test(text)) out.push('#include <cstdint>');
    if (text.includes('std::size_t')) out.push('#include <cstddef>');
    if (out.length > 4) out.push('');
    out.push('namespace cantus {', '');
    for (const l of lines) out.push(...l, '');
    out.push('}  // namespace cantus', '');
  }
  out.push(`#endif  // ${g}`, '');
  return out.join('\n');
}

/** Every generated file of `root`, as relative path -> content, plus counts. */
async function plan(root, loader) {
  const files = new Map();
  const stats = { dirs: 0, specs: 0, tables: 0, limits: 0 };
  for (const dir of moduleDirs(root)) {
    stats.dirs++;
    const specPath = join(root, dir, 'tables.json');
    const lines = [];
    if (existsSync(specPath)) {
      stats.specs++;
      let spec;
      try {
        spec = JSON.parse(readFileSync(specPath, 'utf8'));
      } catch (e) {
        throw new GenError(`${dir}/tables.json: ${e.message}`);
      }
      for (const t of spec.tables ?? []) {
        const file = `${dir}/${snake(t.export ?? '')}.gen.inc`;
        if (files.has(file)) throw new GenError(`${file} is produced twice`);
        files.set(file, await tableFile(loader, dir, t));
        stats.tables++;
      }
      for (const l of spec.limits ?? []) {
        lines.push(await limitLine(loader, dir, l));
        stats.limits++;
      }
    }
    files.set(`${dir}/limits.gen.h`, limitsHeader(dir, lines));
  }
  return { files, stats };
}

/** Generated files on disk under the module dirs of `root`. */
function existingGenerated(root) {
  const out = [];
  for (const dir of moduleDirs(root)) {
    for (const name of readdirSync(join(root, dir))) {
      if (name.endsWith('.gen.inc') || name === 'limits.gen.h') out.push(`${dir}/${name}`);
    }
  }
  return out;
}

/** Differences between the plan and the tree: stale, missing, orphaned files. */
function drift(root, files) {
  const problems = [];
  for (const [file, content] of files) {
    const path = join(root, file);
    if (!existsSync(path)) problems.push(`missing ${file}`);
    else if (readFileSync(path, 'utf8') !== content) problems.push(`stale ${file}`);
  }
  for (const file of existingGenerated(root)) {
    if (!files.has(file)) problems.push(`orphaned ${file}`);
  }
  return problems;
}

function summary(stats) {
  return `${stats.dirs} module dirs, ${stats.specs} tables.json, ${stats.tables} tables, ${stats.limits} limits`;
}

async function run(root, { check, require }) {
  const loader = await createLoader(root);
  try {
    const { files, stats } = await plan(root, loader);
    if (stats.dirs === 0) throw new GenError('no module directories found under src/');
    if (require && stats.specs === 0) throw new GenError('no tables.json found (--require)');
    if (check) {
      const problems = drift(root, files);
      if (problems.length > 0) {
        throw new GenError(`${problems.join('\n')}\nrun: node tools/data/gen_tables.mjs`);
      }
      say(`gen_tables --check: ${summary(stats)}; ${files.size} files up to date`);
    } else {
      for (const [file, content] of files) writeFileSync(join(root, file), content);
      say(`gen_tables: ${summary(stats)}; wrote ${files.size} files`);
    }
  } finally {
    await loader.close();
  }
}

/** Run the generator on the fixture tree and check outputs, drift detection and rejections. */
async function selfTest() {
  // The fixture tree holds its generated files; the literals below pin what they must contain.
  const root = join(HERE, 'fixtures/root');
  const results = [];
  const record = (name, ok, detail = '') => results.push({ name, ok, detail });
  const loader = await createLoader(root);
  try {
    const { files, stats } = await plan(root, loader);
    record(
      'fixture counts',
      stats.dirs === 3 && stats.specs === 1 && stats.tables === 3 && stats.limits === 4,
      summary(stats),
    );
    const contains = (file, text) =>
      record(`${file} has ${text}`, (files.get(file) ?? '').includes(text), files.get(file));
    const sample = 'src/core/sample';
    contains(`${sample}/limits.gen.h`, 'inline constexpr int MAX_ITEMS = 64;');
    contains(`${sample}/limits.gen.h`, 'inline constexpr double kRatio = 0.5;');
    contains(`${sample}/limits.gen.h`, 'inline constexpr double EPS = 1e-9;');
    contains(`${sample}/limits.gen.h`, 'inline constexpr bool ENABLED = true;');
    contains(`${sample}/shapes.gen.inc`, '{"triad", 3, {{1, std::nullopt}, {3, true}}},');
    contains(`${sample}/shapes.gen.inc`, String.raw`{"\303\251\"\\", 2, {}},`);
    contains(
      `${sample}/weights.gen.inc`,
      '{"major", {1, -0.0, std::numeric_limits<double>::quiet_NaN()}},',
    );
    contains(
      `${sample}/weights.gen.inc`,
      '{"minor", {std::numeric_limits<double>::infinity(), 0.1}},',
    );
    contains(`${sample}/default_shape.gen.inc`, '{"unit", 1, {{1, std::nullopt}}}\n');
    contains('src/theory/limits.gen.h', '#define CANTUS_SRC_THEORY_LIMITS_GEN_H_\n\n#endif');
    const clean = drift(root, files);
    record('fixture tree matches the generator', clean.length === 0, clean.join('; '));
    const mutated = new Map(files);
    const first = [...mutated.keys()][0];
    mutated.set(first, `${mutated.get(first)}// drift\n`);
    record('drift is detected', drift(root, mutated).includes(`stale ${first}`));
    const fewer = new Map(files);
    fewer.delete(`${sample}/shapes.gen.inc`);
    record('orphan is detected', drift(root, fewer).includes(`orphaned ${sample}/shapes.gen.inc`));
    const more = new Map(files);
    more.set(`${sample}/extra.gen.inc`, '{}\n');
    record(
      'missing file is detected',
      drift(root, more).includes(`missing ${sample}/extra.gen.inc`),
    );

    const rejects = async (name, fn, pattern) => {
      try {
        await fn();
        record(name, false, 'accepted');
      } catch (e) {
        record(name, e instanceof GenError && pattern.test(e.message), e.message);
      }
    };
    const dir = 'src/core/sample';
    const base = { module: 'core/sample/index.ts' };
    await rejects(
      'fractional integer limit',
      () => limitLine(loader, dir, { ...base, export: 'RATIO', cxx_type: 'int' }),
      /is not a int/,
    );
    await rejects(
      'out-of-range limit',
      () => limitLine(loader, dir, { ...base, export: 'NEGATIVE', cxx_type: 'std::uint32_t' }),
      /is not a std::uint32_t/,
    );
    await rejects(
      'unknown limit type',
      () => limitLine(loader, dir, { ...base, export: 'MAX_ITEMS', cxx_type: 'float' }),
      /cxx_type must be/,
    );
    await rejects(
      'missing export',
      () => limitLine(loader, dir, { ...base, export: 'NOPE', cxx_type: 'int' }),
      /has no export NOPE/,
    );
    await rejects(
      'missing module',
      () => limitLine(loader, dir, { module: 'core/none.ts', export: 'X', cxx_type: 'int' }),
      /does not exist/,
    );
    await rejects(
      'object without fields',
      () =>
        tableFile(loader, dir, {
          ...base,
          export: 'SHAPES',
          cxx_type: 'S',
          cxx_name: 'kS',
          fields: ['name', 'tones'],
        }),
      /needs a "fields" list/,
    );
    await rejects(
      'function value',
      () =>
        tableFile(loader, dir, {
          ...base,
          export: 'HOOKS',
          cxx_type: 'S',
          cxx_name: 'kS',
          fields: [],
        }),
      /cannot write a function/,
    );
    await rejects(
      'record of an array',
      () =>
        tableFile(loader, dir, {
          ...base,
          export: 'SHAPES',
          cxx_type: 'S',
          cxx_name: 'kS',
          form: 'record',
          fields: ['name'],
        }),
      /must be a plain object/,
    );
    await rejects(
      'unknown form',
      () =>
        tableFile(loader, dir, {
          ...base,
          export: 'SHAPES',
          cxx_type: 'S',
          cxx_name: 'kS',
          form: 'row',
          fields: ['name'],
        }),
      /unknown "form"/,
    );
    await rejects(
      'scalar table',
      () =>
        tableFile(loader, dir, {
          ...base,
          export: 'MAX_ITEMS',
          cxx_type: 'S',
          cxx_name: 'kS',
          fields: [],
        }),
      /array or an object/,
    );
  } finally {
    await loader.close();
  }
  for (const r of results) {
    say(`${r.ok ? 'ok  ' : 'FAIL'} ${r.name}${r.ok || !r.detail ? '' : `\n     ${r.detail}`}`);
  }
  const failed = results.filter((r) => !r.ok).length;
  say(`gen_tables --self-test: ${results.length - failed}/${results.length} passed`);
  if (results.length === 0 || failed > 0) process.exit(1);
}

const argv = process.argv.slice(2);
try {
  if (argv.includes('--self-test')) {
    await selfTest();
  } else {
    const at = argv.indexOf('--root');
    const root = at >= 0 ? resolve(argv[at + 1]) : REPO_ROOT;
    await run(root, { check: argv.includes('--check'), require: argv.includes('--require') });
  }
} catch (e) {
  if (e instanceof GenError) {
    console.error(`gen_tables: ${e.message}`);
    process.exit(1);
  }
  throw e;
}
