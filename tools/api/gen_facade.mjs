#!/usr/bin/env node
/**
 * Generate the TS facade's export modules from `api/manifest.json`.
 *
 * Writes bindings/js/src/generated/:
 *   meta.ts      model classes, the by-reference types, and the hybrid / handle types with their
 *                members, payload and stable properties
 *   api.ts       every export: functions and classes call ops, consts decode consts.json
 *   <layer>.ts   one re-export list per layer subpath
 *   consts.json  the wire form of every const and enum, as the pure TS package evaluates it
 *
 * Consts are evaluated here rather than fetched at import, so importing the facade makes no op
 * call and works against a core that registers only part of the API.
 *
 * Usage: node tools/api/gen_facade.mjs [--check]
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ANNOTATIONS, fail as failTool, MANIFEST, REPO } from '../corpus/lib.mjs';
import { factoryOf } from './factory.mjs';

const OUT = path.join(REPO, 'bindings/js/src/generated');
const BIOME = path.join(REPO, 'node_modules/.bin/biome');
const HEADER = '// Generated by tools/api/gen_facade.mjs from api/manifest.json; do not edit.';
const LAYERS = ['core', 'theory', 'analyze', 'generate', 'model'];

function fail(message) {
  failTool('gen_facade', message);
}

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;

function metaModule(manifest, annotations) {
  const classes = manifest.exports.filter((e) => e.kind === 'class').map((e) => e.id);
  const lines = [HEADER, "import type { TypeMeta } from '../runtime.js';", ''];
  lines.push(
    '/** A hybrid or handle type, with the payload fields a hybrid carries on the wire. */',
  );
  lines.push('export type TypeInfo = TypeMeta & { payload: readonly string[] };', '');
  lines.push('/** The model classes, whose instances cross as `$class`. */');
  lines.push(`export const CLASSES: readonly string[] = [${classes.map(q).join(', ')}];`, '');
  const wire = Object.fromEntries(
    Object.entries(annotations.class_wire ?? {}).filter(([name]) => name !== 'description'),
  );
  for (const name of Object.keys(wire))
    if (!classes.includes(name)) fail(`class_wire names unknown class ${name}`);
  lines.push(
    '/** How a model class crosses when its wire form is not `{"$class", ...toJSON()}`. */',
  );
  lines.push('export type ClassWire = {');
  lines.push('  extra?: Readonly<Record<string, string>>;');
  lines.push('  context?: Readonly<Record<string, string>>;');
  lines.push('  fields?: Readonly<Record<string, string>>;');
  lines.push('  array?: string;');
  lines.push('};', '');
  lines.push(
    `export const CLASS_WIRE: Readonly<Record<string, ClassWire>> = ${JSON.stringify(wire)};`,
    '',
  );
  const byReference = annotations.by_reference ?? [];
  for (const name of byReference) {
    const known = classes.includes(name) || manifest.types.some((t) => t.id === name);
    if (!known) fail(`by_reference names unknown class or hybrid ${name}`);
  }
  lines.push(
    '/** The types whose instances a host holds in the core once and sends by reference. */',
  );
  lines.push(`export const BY_REFERENCE: readonly string[] = [${byReference.map(q).join(', ')}];`);
  lines.push('');
  lines.push('/** The hybrid and handle types. */');
  lines.push('export const TYPES: Readonly<Record<string, TypeInfo>> = {');
  for (const t of manifest.types) {
    const info = annotations.classification[t.kind][t.id] ?? {};
    const methods = t.members.filter((m) => m.kind === 'method').map((m) => m.name);
    const properties = t.members.filter((m) => m.kind === 'property').map((m) => m.name);
    const payload = info.payload ?? [];
    const stable = info.stable ?? [];
    if (stable.length > 0 && t.kind !== 'handle') fail(`${t.id}: stable applies to handles only`);
    for (const name of stable) {
      if (!properties.includes(name))
        fail(`${t.id}: stable names ${name}, which is not a property`);
    }
    lines.push(`  ${t.id}: {`);
    lines.push(`    kind: ${q(t.kind)},`);
    lines.push(`    methods: [${methods.map(q).join(', ')}],`);
    lines.push(`    properties: [${properties.map(q).join(', ')}],`);
    lines.push(`    order: [${t.members.map((m) => q(m.name)).join(', ')}],`);
    lines.push(`    payload: [${payload.map(q).join(', ')}],`);
    if (t.kind === 'handle') lines.push(`    stable: [${stable.map(q).join(', ')}],`);
    lines.push('  },');
  }
  lines.push('};', '');
  return lines.join('\n');
}

function classBlock(e) {
  const lines = [`export class ${e.id} {`];
  if (e.constructor.private) {
    // No constructor op is registered; instances come from the factory.
    lines.push('  constructor() {');
    lines.push(
      `    throw new TypeError(${q(`${e.id} has no public constructor; use ${factoryOf(e)}`)});`,
    );
  } else {
    lines.push('  constructor(...args: unknown[]) {');
    lines.push(`    runtime.construct(this, ${q(`${e.id}.constructor`)}, args);`);
  }
  lines.push('  }');
  for (const m of e.members) {
    if (!IDENT.test(m.name)) fail(`${e.id}.${m.name}: member name is not an identifier`);
    const op = `${e.id}${m.static ? '.' : '#'}${m.name}`;
    const prefix = m.static ? 'static ' : '';
    const self = m.static ? 'args' : '[this, ...args]';
    lines.push('');
    if (m.kind === 'method') {
      lines.push(`  ${prefix}${m.name}(...args: unknown[]): unknown {`);
      lines.push(`    return runtime.call(${q(op)}, ${self});`);
    } else {
      lines.push(`  ${prefix}get ${m.name}(): unknown {`);
      lines.push(`    return runtime.call(${q(op)}, ${m.static ? '[]' : '[this]'});`);
    }
    lines.push('  }');
  }
  if (e.iterable) {
    lines.push('');
    lines.push('  [Symbol.iterator](): Iterator<unknown> {');
    lines.push(
      `    return (runtime.call(${q(`${e.id}#${e.iterable}`)}, [this]) as Iterable<unknown>)[Symbol.iterator]();`,
    );
    lines.push('  }');
  }
  lines.push('}');
  const lengths = (isStatic) =>
    e.members
      .filter((m) => m.kind === 'method' && m.static === isStatic)
      .map((m) => `${m.name}: ${m.length}`)
      .join(', ');
  lines.push(
    `runtime.registerClass(${q(e.id)}, ${e.id}, { constructor: ${e.constructor.length}, static: { ${lengths(true)} }, prototype: { ${lengths(false)} } });`,
  );
  return lines.join('\n');
}

function apiModule(manifest, annotations) {
  const local = new Set((annotations.facade_local ?? []).map((e) => e.id));
  const errorsTs = [];
  const lines = [
    HEADER,
    "import type * as Pure from '../../../../ts/src/index.js';",
    "import { runtime } from '../default-runtime.js';",
    "import CONSTS from './consts.json' with { type: 'json' };",
    '',
    'type ConstEntry = { frozen: boolean; wire: unknown };',
    'const consts = CONSTS as unknown as Record<string, ConstEntry>;',
    '',
    'function op<T>(name: string, length: number): T {',
    '  return runtime.fn(name, length) as T;',
    '}',
    '',
    'function constant<T>(name: string): T {',
    '  const entry = consts[name] as ConstEntry;',
    '  return runtime.constant(entry.wire, entry.frozen) as T;',
    '}',
    '',
  ];
  const blocks = [];
  for (const e of manifest.exports) {
    if (e.kind === 'error' || local.has(e.id)) {
      errorsTs.push(e.id);
      continue;
    }
    if (e.kind === 'function') {
      blocks.push(`export const ${e.id}: typeof Pure.${e.id} = op(${q(e.id)}, ${e.length});`);
    } else if (e.kind === 'const' || e.kind === 'enum') {
      blocks.push(`export const ${e.id}: typeof Pure.${e.id} = constant(${q(e.id)});`);
    } else if (e.kind === 'class') {
      blocks.push(`\n${classBlock(e)}\n`);
    } else {
      fail(`${e.id}: unsupported kind ${e.kind}`);
    }
  }
  lines.push(...blocks);
  lines.push('');
  lines.push(`export { ${errorsTs.sort().join(', ')} } from '../errors.js';`);
  lines.push('');
  return lines.join('\n').replace(/\n{3,}/g, '\n\n');
}

function layerModule(manifest, layer) {
  const ids = manifest.exports.filter((e) => e.subpaths.includes(layer)).map((e) => e.id);
  if (ids.length === 0) fail(`no exports on subpath ${layer}`);
  return `${HEADER}\nexport {\n${ids.map((id) => `  ${id},`).join('\n')}\n} from './api.js';\n`;
}

/** Whether every object reachable from `value` (class instances aside) is frozen, none, or mixed. */
function frozenState(value, isClass) {
  let frozen = 0;
  let open = 0;
  const seen = new Set();
  const visit = (v) => {
    if (typeof v !== 'object' || v === null || seen.has(v) || isClass(v)) return;
    seen.add(v);
    if (Object.isFrozen(v)) frozen += 1;
    else open += 1;
    for (const child of Object.values(v)) visit(child);
  };
  visit(value);
  if (open === 0) return true;
  if (frozen === 0) return false;
  return 'mixed';
}

/** Evaluate every const through the pure TS backend, as its `$const:` op would answer. */
async function evaluateConsts(manifest) {
  const { createServer, createServerModuleRunner } = await import('vite');
  delete process.env.CANTUS_RECORD;
  const server = await createServer({
    root: REPO,
    configFile: false,
    logLevel: 'error',
    server: { middlewareMode: true, hmr: false, ws: false },
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  const runner = createServerModuleRunner(server.environments.ssr, { hmr: false });
  try {
    const pure = await runner.import(path.join(REPO, 'ts/src/index.ts'));
    const { backend } = await runner.import(path.join(REPO, 'bindings/js/src/backends/ts.ts'));
    const classes = manifest.exports.filter((e) => e.kind === 'class').map((e) => pure[e.id]);
    const isClass = (v) => classes.some((c) => v instanceof c);
    const out = {};
    const mixed = [];
    for (const e of manifest.exports) {
      if (e.kind !== 'const' && e.kind !== 'enum') continue;
      const reply = backend.call(`$const:${e.id}`, '[]', null);
      if (reply.status !== 0) fail(`$const:${e.id} failed: ${reply.json}`);
      if (/"\$(h|ref|cb)"/.test(reply.json)) fail(`${e.id}: a const carries a handle or reference`);
      const frozen = frozenState(pure[e.id], isClass);
      if (frozen === 'mixed') mixed.push(e.id);
      out[e.id] = { frozen: frozen === true, wire: JSON.parse(reply.json) };
    }
    if (mixed.length > 0) fail(`partly frozen consts: ${mixed.join(', ')}`);
    return out;
  } finally {
    await runner.close();
    await server.close();
  }
}

/** `text` as the repo's biome configuration formats a file at `name` under generated/. */
function format(name, text) {
  return execFileSync(BIOME, ['check', '--write', `--stdin-file-path=${path.join(OUT, name)}`], {
    cwd: REPO,
    input: text,
    encoding: 'utf8',
    maxBuffer: 1 << 28,
  });
}

async function main() {
  const check = process.argv.includes('--check');
  for (const arg of process.argv.slice(2)) if (arg !== '--check') fail(`unknown argument ${arg}`);
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const annotations = JSON.parse(readFileSync(ANNOTATIONS, 'utf8'));
  const files = new Map();
  files.set('meta.ts', metaModule(manifest, annotations));
  files.set('api.ts', apiModule(manifest, annotations));
  for (const layer of LAYERS) files.set(`${layer}.ts`, layerModule(manifest, layer));
  // The backend that evaluates the consts reads meta.ts, so a first run writes it beforehand.
  if (!check) {
    mkdirSync(OUT, { recursive: true });
    writeFileSync(path.join(OUT, 'meta.ts'), format('meta.ts', files.get('meta.ts')));
  }
  const consts = await evaluateConsts(manifest);
  files.set('consts.json', `${JSON.stringify(consts, null, 1)}\n`);

  for (const [name, text] of files) files.set(name, format(name, text));

  const stale = [];
  for (const [name, text] of files) {
    const file = path.join(OUT, name);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === text) continue;
    if (check) stale.push(name);
    else writeFileSync(file, text);
  }
  const orphans = existsSync(OUT) ? readdirSync(OUT).filter((f) => !files.has(f)) : [];
  if (check) {
    if (stale.length > 0 || orphans.length > 0) {
      fail(
        `stale: ${[...stale, ...orphans.map((o) => `${o} (orphan)`)].join(', ')}; run node tools/api/gen_facade.mjs`,
      );
    }
    process.stdout.write(
      `gen_facade: up to date (${files.size} files, ${manifest.exports.length} exports)\n`,
    );
    return;
  }
  if (orphans.length > 0) fail(`orphaned files in generated/: ${orphans.join(', ')}`);
  process.stdout.write(
    `gen_facade: wrote ${files.size} files (${manifest.exports.length} exports)\n`,
  );
}

await main();
