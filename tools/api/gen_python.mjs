#!/usr/bin/env node
/**
 * Generate the Python binding's export modules from `api/manifest.json`.
 *
 * Writes bindings/python/src/libcantus/:
 *   _generated.py   one function per function export (snake_case), one class per model class,
 *                   hybrid and handle type; constants are read on first access
 *   _generated.pyi  the same signatures for type checkers, plus the constant names
 *
 * A parameter the manifest marks as an option bag (`bag`, decided by the extractor) becomes
 * keyword-only arguments defaulting to None (None means absent); every other parameter stays
 * positional, with `UNSET` as the default of an optional one. A bag that is not the last
 * parameter is packed in place by `_options`, which yields `UNSET` when no option is given.
 *
 * Usage: node tools/api/gen_python.mjs [--check]
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ANNOTATIONS, fail as failTool, MANIFEST, REPO } from '../corpus/lib.mjs';
import { factoryOf } from './factory.mjs';

const OUT = path.join(REPO, 'bindings/python/src/libcantus');
const NOTICE = 'Generated by tools/api/gen_python.mjs from api/manifest.json; do not edit.';
const LINE = 100;
// Names the base classes already define.
const RESERVED = { Model: [], Hybrid: [], Handle: ['close', 'closed'] };

const KEYWORDS = new Set(
  (
    'False None True and as assert async await break class continue def del elif else except ' +
    'finally for from global if import in is lambda nonlocal not or pass raise return try while ' +
    'with yield match case type'
  ).split(' '),
);

function fail(message) {
  failTool('gen_python', message);
}

const q = (s) => JSON.stringify(s);

function snake(name) {
  const s = name
    .replace(/(.)([A-Z][a-z]+)/g, '$1_$2')
    .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
    .toLowerCase();
  return KEYWORDS.has(s) ? `${s}_` : s;
}

/** Split a manifest parameter list into positional parameters, a rest parameter and an option bag. */
function shape(owner, params) {
  const list = [...params];
  let bag = null;
  let bagAt = null;
  const at = list.findIndex((p) => p.bag);
  if (at >= 0) {
    const [param] = list.splice(at, 1);
    const seen = new Set();
    bag = param.bag.map((field) => {
      const py = snake(field);
      if (seen.has(py)) fail(`${owner}: option fields collide on ${py}`);
      seen.add(py);
      return { wire: field, py };
    });
    // A bag followed by other parameters is packed where it stands.
    if (at < list.length) bagAt = at;
  }
  const names = new Set();
  const positional = [];
  let rest = null;
  for (const p of list) {
    const py = snake(p.name);
    if (names.has(py)) fail(`${owner}: parameter name ${py} is used twice`);
    names.add(py);
    if (p.rest) rest = py;
    else positional.push({ py, optional: p.optional });
  }
  return { positional, rest, bag, bagAt };
}

/** The `def` header lines of a callable. */
function header({ indent, name, lead, sig, stub, returns = 'Any' }) {
  const items = [...lead];
  for (const p of sig.positional) {
    items.push(p.optional ? `${p.py}: Any = ${stub ? '...' : 'UNSET'}` : `${p.py}: Any`);
  }
  if (sig.positional.length > 0) items.push('/');
  if (sig.rest !== null) items.push(`*${sig.rest}: Any`);
  else if (sig.bag) items.push('*');
  for (const f of sig.bag ?? []) items.push(`${f.py}: Any = ${stub ? '...' : 'None'}`);
  const tail = stub ? `) -> ${returns}: ...` : `) -> ${returns}:`;
  const flat = `${indent}def ${name}(${items.join(', ')}${tail}`;
  if (flat.length <= LINE) return [flat];
  return [`${indent}def ${name}(`, ...items.map((i) => `${indent}    ${i},`), `${indent}${tail}`];
}

/**
 * The statement calling the runtime: `<statement><call>(<before>, op, [args], {bag})`, where the
 * bag maps wire option names to the keyword arguments.
 */
function callLines({ indent, statement = 'return ', call, before = [], op, selfArg, sig }) {
  const fields = () => `{${(sig.bag ?? []).map((f) => `${q(f.wire)}: ${f.py}`).join(', ')}}`;
  const names = sig.positional.map((p) => p.py);
  if (sig.bagAt !== null) names.splice(sig.bagAt, 0, `_options(${fields()})`);
  const args = [...selfArg, ...names];
  if (sig.rest !== null) args.push(`*${sig.rest}`);
  const items = [...before, q(op), `[${args.join(', ')}]`];
  const trailing = sig.bag && sig.bagAt === null;
  const bag = trailing ? fields() : null;
  const flat = `${indent}${statement}${call}(${[...items, ...(bag ? [bag] : [])].join(', ')})`;
  if (flat.length <= LINE) return [flat];
  const inner = `${indent}    `;
  const out = [`${indent}${statement}${call}(`, ...items.map((i) => `${inner}${i},`)];
  if (trailing) {
    out.push(`${inner}{`);
    for (const f of sig.bag) out.push(`${inner}    ${q(f.wire)}: ${f.py},`);
    out.push(`${inner}},`);
  }
  out.push(`${indent})`);
  return out;
}

function checkMembers(owner, members, base) {
  const seen = new Set(RESERVED[base]);
  for (const m of members) {
    const py = snake(m.name);
    if (!/^[a-z][a-z0-9_]*$/.test(py)) fail(`${owner}.${m.name}: ${py} is not a plain name`);
    if (seen.has(py)) fail(`${owner}.${m.name}: ${py} is defined twice`);
    seen.add(py);
  }
}

function functionBlock(e) {
  const sig = shape(e.id, e.params);
  const name = snake(e.id);
  const py = [
    ...header({ indent: '', name, lead: [], sig, stub: false }),
    ...callLines({ indent: '    ', call: 'runtime.call', op: e.id, selfArg: [], sig }),
  ];
  return { py, pyi: header({ indent: '', name, lead: [], sig, stub: true }) };
}

/** A method or getter of a class, hybrid or handle. */
function memberBlock(owner, base, m, stable = new Set()) {
  const name = snake(m.name);
  const op = `${owner}${m.static ? '.' : '#'}${m.name}`;
  const call = base === 'Handle' ? 'self._call' : 'runtime.call';
  const selfArg = m.static ? [] : ['self'];
  const lead = m.static ? [] : ['self'];
  const decorator = [];
  let sig;
  if (m.kind === 'getter' || m.kind === 'property') {
    if (m.static) {
      return { py: [`    ${name} = StaticGetter(${q(op)})`], pyi: [`    ${name}: ClassVar[Any]`] };
    }
    if (base === 'Hybrid') return { py: [], pyi: [`    ${name}: Any`] };
    decorator.push('    @property');
    sig = { positional: [], rest: null, bag: null, bagAt: null };
    if (base === 'Handle' && stable.has(m.name)) {
      return {
        py: [
          ...decorator,
          ...header({ indent: '    ', name, lead, sig, stub: false }),
          `        return self._stable(${q(name)}, ${q(op)})`,
        ],
        pyi: [...decorator, ...header({ indent: '    ', name, lead, sig, stub: true })],
      };
    }
  } else {
    if (m.static) decorator.push('    @staticmethod');
    sig = shape(op, m.params ?? []);
  }
  return {
    py: [
      ...decorator,
      ...header({ indent: '    ', name, lead, sig, stub: false }),
      ...callLines({ indent: '        ', call, op, selfArg, sig }),
    ],
    pyi: [...decorator, ...header({ indent: '    ', name, lead, sig, stub: true })],
  };
}

/** Join member blocks: blank lines between definitions in the module, none in the stub. */
function joinMembers(blocks) {
  const py = [];
  for (const b of blocks) {
    if (b.py.length === 0) continue;
    if (py.length > 0) py.push('');
    py.push(...b.py);
  }
  return { py, pyi: blocks.flatMap((b) => b.pyi) };
}

function classLines(name, base, head, members) {
  const { py, pyi } = joinMembers(members);
  return {
    py: [
      `class ${name}(${base}):`,
      ...head,
      ...(head.length > 0 && py.length > 0 ? [''] : []),
      ...py,
    ],
    pyi: [`class ${name}(${base}):`, ...(pyi.length > 0 ? pyi : ['    ...'])],
  };
}

function modelBlock(e) {
  checkMembers(e.id, e.members, 'Model');
  const blocks = [];
  if (e.constructor?.private) {
    // No constructor op is registered; the stub does not advertise a constructor.
    blocks.push({
      py: [
        '    def __init__(self, *args: Any, **kwargs: Any) -> None:',
        `        raise TypeError(${q(`${e.id} has no public constructor; use ${factoryOf(e)}`)})`,
      ],
      pyi: [],
    });
  } else if (e.constructor?.params) {
    const op = `${e.id}.constructor`;
    const sig = shape(op, e.constructor.params);
    const spec = { indent: '    ', name: '__init__', lead: ['self'], sig, returns: 'None' };
    blocks.push({
      py: [
        ...header({ ...spec, stub: false }),
        ...callLines({
          indent: '        ',
          statement: '',
          call: 'runtime.construct',
          before: ['self'],
          op,
          selfArg: [],
          sig,
        }),
      ],
      pyi: header({ ...spec, stub: true }),
    });
  }
  for (const m of e.members) blocks.push(memberBlock(e.id, 'Model', m));
  if (e.iterable) {
    blocks.push({
      py: [
        '    def __iter__(self) -> Iterator[Any]:',
        `        return iter(runtime.call(${q(`${e.id}#${e.iterable}`)}, [self]))`,
      ],
      pyi: ['    def __iter__(self) -> Iterator[Any]: ...'],
    });
  }
  return classLines(e.id, 'Model', [], blocks);
}

function typeBlock(t, annotations) {
  const base = t.kind === 'handle' ? 'Handle' : 'Hybrid';
  checkMembers(t.id, t.members, base);
  const stable = new Set(annotations.classification?.[t.kind]?.[t.id]?.stable ?? []);
  for (const name of stable) {
    const member = t.members.find((m) => m.name === name);
    if (base !== 'Handle' || member?.kind !== 'property') {
      fail(`${t.id}: stable names ${name}, which is not a handle property`);
    }
  }
  const blocks = t.members.map((m) => memberBlock(t.id, base, m, stable));
  const head = [];
  if (base === 'Handle') {
    head.push(`    _TYPE = ${q(t.id)}`);
  } else {
    const fields = t.members.filter((m) => m.kind === 'property').map((m) => m.name);
    const pairs = fields.map((f) => `(${q(f)}, ${q(snake(f))})`);
    const flat = `    _FIELDS = (${pairs.join(', ')}${pairs.length === 1 ? ',' : ''})`;
    if (flat.length <= LINE) head.push(flat);
    else head.push('    _FIELDS = (', ...pairs.map((p) => `        ${p},`), '    )');
    if (fields.length > 0) head.push('', ...fields.map((f) => `    ${snake(f)}: Any`));
  }
  return classLines(t.id, base, head, blocks);
}

function build(manifest, annotations) {
  const local = new Set((annotations.facade_local ?? []).map((e) => e.id));
  const functions = [];
  const models = [];
  const constants = [];
  const names = new Map();
  const claim = (py, id) => {
    if (names.has(py)) fail(`${id} and ${names.get(py)} both export ${py}`);
    names.set(py, id);
  };
  for (const e of manifest.exports) {
    if (e.kind === 'error' || local.has(e.id)) continue;
    if (e.kind === 'function') {
      claim(snake(e.id), e.id);
      functions.push(e);
    } else if (e.kind === 'class') {
      claim(e.id, e.id);
      models.push(e);
    } else if (e.kind === 'const' || e.kind === 'enum') {
      claim(e.id, e.id);
      constants.push(e.id);
    } else {
      fail(`${e.id}: unsupported kind ${e.kind}`);
    }
  }
  for (const t of manifest.types) claim(t.id, t.id);
  functions.sort((a, b) => (snake(a.id) < snake(b.id) ? -1 : 1));

  const py = [`"""${NOTICE}"""`, '', 'from __future__ import annotations', ''];
  const pyi = [`# ${NOTICE}`, ''];
  const hasIter = models.some((m) => m.iterable);
  const iterImport = hasIter ? ['from collections.abc import Iterator'] : [];
  py.push(...iterImport, 'from typing import Any', '');
  pyi.push(...iterImport, 'from typing import Any, ClassVar', '');
  py.push('from ._codec import UNSET, Handle, Hybrid, Model, StaticGetter, freeze, runtime', '');
  pyi.push('from ._codec import Handle, Hybrid, Model', '');

  const blocks = functions.map(functionBlock);
  const classes = [
    ...models.map(modelBlock),
    ...manifest.types.map((t) => typeBlock(t, annotations)),
  ];
  const typeNames = [...models.map((m) => m.id), ...manifest.types.map((t) => t.id)];
  // Constants first, then classes, then the rest, each alphabetical (ruff's isort-style order).
  const group = (n) => (n === n.toUpperCase() ? 0 : /^[A-Z]/.test(n) ? 1 : 2);
  const order = (a, b) => group(a) - group(b) || (a < b ? -1 : a > b ? 1 : 0);
  const exported = [...functions.map((f) => snake(f.id)), ...typeNames].sort(order);

  py.push('__all__ = [', ...exported.map((n) => `    ${q(n)},`), ']', '');
  pyi.push(
    '__all__ = [',
    ...[...exported, ...constants].sort(order).map((n) => `    ${q(n)},`),
    ']',
    '',
  );

  py.push(
    'CONSTANTS: frozenset[str] = frozenset(',
    '    {',
    ...constants.map((c) => `        ${q(c)},`),
    '    }',
    ')',
    '',
  );
  py.push('_constants: dict[str, Any] = {}', '', '');
  if ([...blocks, ...classes].some((b) => b.py.some((l) => l.includes('_options(')))) {
    py.push(
      'def _options(bag: dict[str, Any]) -> Any:',
      '    """The options that were given, or UNSET when none was."""',
      '    given = {k: v for k, v in bag.items() if v is not None}',
      '    return given or UNSET',
      '',
      '',
    );
  }
  py.push(
    'def constant(name: str) -> Any:',
    '    """The value of constant ``name``, read from the core on first access."""',
    '    if name not in CONSTANTS:',
    '        raise AttributeError(f"module \'libcantus\' has no attribute {name!r}")',
    '    if name not in _constants:',
    '        _constants[name] = freeze(runtime.call(f"$const:{name}", []))',
    '    return _constants[name]',
    '',
    '',
  );
  pyi.push('CONSTANTS: frozenset[str]', '', 'def constant(name: str) -> Any: ...', '');
  for (const c of constants) pyi.push(`${c}: Any`);
  pyi.push('');

  for (const b of blocks) {
    py.push(...b.py, '', '');
    pyi.push(...b.pyi);
  }
  for (const c of classes) {
    py.push(...c.py, '', '');
    pyi.push('', ...c.pyi);
  }
  py.push('runtime.register(', ...typeNames.map((n) => `    ${n},`), ')');
  const byReference = annotations.by_reference ?? [];
  for (const name of byReference) {
    if (!typeNames.includes(name)) fail(`by_reference names unknown class or hybrid ${name}`);
  }
  py.push(`runtime.by_reference(${byReference.map(q).join(', ')})`);
  return {
    py: `${py.join('\n').replace(/\n{4,}/g, '\n\n\n')}\n`,
    pyi: `${pyi.join('\n').replace(/\n{4,}/g, '\n\n\n')}\n`,
  };
}

function main() {
  const check = process.argv.includes('--check');
  for (const arg of process.argv.slice(2)) if (arg !== '--check') fail(`unknown argument ${arg}`);
  const manifest = JSON.parse(readFileSync(MANIFEST, 'utf8'));
  const annotations = JSON.parse(readFileSync(ANNOTATIONS, 'utf8'));
  const { py, pyi } = build(manifest, annotations);
  const files = new Map([
    ['_generated.py', py],
    ['_generated.pyi', pyi],
  ]);
  const stale = [];
  for (const [name, text] of files) {
    const file = path.join(OUT, name);
    const current = existsSync(file) ? readFileSync(file, 'utf8') : null;
    if (current === text) continue;
    if (check) stale.push(name);
    else writeFileSync(file, text);
  }
  if (check) {
    if (stale.length > 0) fail(`stale: ${stale.join(', ')}; run node tools/api/gen_python.mjs`);
    process.stdout.write(`gen_python: up to date (${manifest.exports.length} exports)\n`);
    return;
  }
  process.stdout.write(
    `gen_python: wrote ${files.size} files (${manifest.exports.length} exports)\n`,
  );
}

main();
