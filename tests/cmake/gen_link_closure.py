#!/usr/bin/env python3
"""Write link_closure.cpp for one static archive from its member list.

The program itself calls nothing: the archive is linked in whole, so the check is whether every
member resolves against the target's declared link interface. The member list goes into the
source so the build log records what was forced in, and an empty archive fails here.
"""

import argparse
import subprocess
import sys
from pathlib import Path


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--archive", required=True)
    parser.add_argument("--ar", default="ar")
    parser.add_argument("--out", required=True)
    args = parser.parse_args()

    listing = subprocess.run(
        [args.ar, "t", args.archive], check=True, capture_output=True, text=True
    ).stdout.split()
    members = sorted(m for m in listing if m.endswith(".o"))
    if not members:
        print(f"gen_link_closure: no object members in {args.archive}", file=sys.stderr)
        return 1
    lines = [
        f"// Generated by tests/cmake/gen_link_closure.py from {Path(args.archive).name}.",
        f"// {len(members)} members, all force-linked:",
        *(f"//   {m}" for m in members),
        "",
        "int main() { return 0; }",
        "",
    ]
    Path(args.out).write_text("\n".join(lines))
    print(f"gen_link_closure: {Path(args.archive).name}: {len(members)} members")
    return 0


if __name__ == "__main__":
    sys.exit(main())
